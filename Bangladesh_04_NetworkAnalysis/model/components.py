class Bridge(Infra):
    """
    Creates delay time

    Attributes
    __________
    condition:
        condition of the bridge

    delay_time: int
        the delay (in ticks) caused by this bridge
    ...

    """

    def __init__(self, unique_id, model, length=0,
                 name='Unknown', road_name='Unknown', condition='Unknown'):
        super().__init__(unique_id, model, length, name, road_name)

        self.condition = condition
        # Track total delay caused by this bridge
        self.total_delay_time = 0
        # bridges start intact; flood event triggers failures dynamically
        self.is_broken = False
        self.broke_during_flood = False  # True if bridge failed during a flood event

    # called by model._trigger_flood() at flood tick
    def trigger_failure(self, failure_prob):
        """
        Roll against failure_prob (0–1). If the bridge is currently intact and
        the roll fails, mark it broken and record that it broke during a flood.
        Returns True if the bridge just broke, False otherwise.
        """
        if not self.is_broken:
            if self.random.random() < failure_prob:
                self.is_broken = True
                self.broke_during_flood = True
                return True
        return False


    def get_delay_time(self):
        """
        Calculates the delay time for a truck based on bridge length,
        only if the bridge breaks down according to its condition probability.
        """
          
        if self.is_broken:
            # Assign the value to 'delay' instead of returning it immediately
            if self.length > 200:
                delay = int(self.random.triangular(60, 240, 120)) 
            elif self.length >= 50:
                delay = self.random.randint(45, 90)
            elif self.length >= 10:
                delay = self.random.randint(15, 60)
            else:
                delay = self.random.randint(10, 20)

            self.total_delay_time += delay  

            return delay
        else: 
        # If the random number is higher, the bridge is fine. No delay.
            return 0
