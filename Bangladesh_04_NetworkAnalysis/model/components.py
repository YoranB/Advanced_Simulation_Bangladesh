class Source(Infra):
    """
    Source generates vehicles

    Class Attributes:
    -----------------
    truck_counter : int
        the number of trucks generated by ALL sources. Used as Truck ID!

    Attributes
    __________
    generation_frequency: int
        the frequency (the number of ticks) by which a truck is generated

    vehicle_generated_flag: bool
        True when a Truck is generated in this tick; False otherwise
    ...

    """

    truck_counter = 0
    generation_frequency = 5  # default fallback (used when no AADT data available)
    vehicle_generated_flag = False

    # accept truck_aadt so each source generates at a road-proportional rate
    def __init__(self, unique_id, model, length=0, name='Unknown', road_name='Unknown', truck_aadt=None):
        super().__init__(unique_id, model, length, name, road_name)
        if truck_aadt is not None and truck_aadt > 0:
            # Convert daily AADT to per-minute rate, then to ticks-per-truck.
            # AADT / 1440 min/day = trucks per minute. Invert for ticks between trucks.
            trucks_per_minute = truck_aadt / 1440.0
            self.generation_frequency = max(1, min(60, int(round(1.0 / trucks_per_minute))))
        # else: keep class-level default of 5

    def step(self):
        if self.model.schedule.steps % self.generation_frequency == 0:
            self.generate_truck()
        else:
            self.vehicle_generated_flag = False

    def generate_truck(self):
        """
        Generates a truck, sets its path, increases the global and local counters
        """
        try:
            agent = Vehicle('Truck' + str(Source.truck_counter), self.model, self)
            if agent:
                self.model.schedule.add(agent)
                agent.set_path()
                Source.truck_counter += 1
                self.vehicle_count += 1
                self.vehicle_generated_flag = True
                #print(str(self) + " GENERATE " + str(agent))
        except Exception as e:
            print("Oops!", e.__class__, "occurred.")


